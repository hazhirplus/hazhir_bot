def fmt_price(n: int) -> str:
    return f"{n:,} تومان"


def fmt_gb_num(gb) -> str:
    """Format a GB value without a trailing .0: 2 -> '2', 0.5 -> '0.5'."""
    try:
        return "%g" % float(gb)
    except (TypeError, ValueError):
        return str(gb)


def fmt_gb(b: int | None) -> str:
    if not b:
        return "نامحدود"
    from panel import bytes_to_gb
    return f"{bytes_to_gb(b):g} گیگ"


